function poster(
  row: Pick<Person, "id" | "name" | "trade" | "city" | "state" | "years" | "bio" | "specialties"> & {
    level?: Person["level"];
    youtube: string;
    veteran?: Person["veteran"];
  },
): Person {
  const still = youtubeThumb(row.youtube);
  return {
    id: row.id,
    name: row.name,
    trade: row.trade,
    level: row.level ?? "Journeyman",
    city: row.city,
    state: row.state,
    years: row.years,
    travelMiles: 40,
    availability: "open",
    bio: row.bio,
    photo: still,
    cover: still,
    specialties: row.specialties,
    tickets: [{ id: "t1", name: "Posted this work", issuer: "Expedite Consults LLC" }],
    history: [{ id: "h1", name: "Posted this work", role: "On camera", when: "2026", city: row.city }],
    example: true,
    ...(row.veteran ? { veteran: row.veteran } : {}),
  };
}

