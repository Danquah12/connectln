function beltOf(src: ClipSource): ClipBelt {
  return src.belt ?? "americas";
}

function topicRank(src: ClipSource) {
  return src.topic === "training" || src.topic === "work" || src.topic === "care" ? 0 : 1;
}

/** Home belt first (training/care), then a thin slice of the other two so the hall is not one country. */
export function sourcesForBelt(belt: ClipBelt, homeCap = 36, awayCap = 20): ClipSource[] {
  const home = CLIP_SOURCES.filter((s) => beltOf(s) === belt).sort((a, b) => topicRank(a) - topicRank(b));
  const away = CLIP_SOURCES.filter((s) => beltOf(s) !== belt).sort((a, b) => topicRank(a) - topicRank(b));
  return [...home.slice(0, homeCap), ...away.slice(0, awayCap)];
}