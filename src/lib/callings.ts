function idFor(trade: Trade) {
  return `seat-${trade.toLowerCase().replace(/[^a-z]+/g, "-")}`;
}

export const callingPeople: Person[] = SEATS.map((s) => ({
  id: idFor(s.trade),
  name: s.name,
  trade: s.trade,
  level: s.level,
  city: s.city,
  state: s.state,
  years: s.years,
  rate: s.rate,
  travelMiles: 40,
  availability: "open" as const,
  bio: s.line,
  photo: youtubeThumb(s.youtube),
  cover: youtubeThumb(s.youtube, "wide"),
  specialties: [s.ticket],
  offers: [s.line],
  needs: ["A shop that reads the card"],
  tickets: [{ id: `${idFor(s.trade)}-t`, name: s.ticket, issuer: s.issuer, verify: "verified" as const }],
  history: [
    {
      id: `${idFor(s.trade)}-h`,
      name: s.house,
      role: s.level,
      when: `${s.years} years`,
      city: s.city,
    },
  ],
}));

